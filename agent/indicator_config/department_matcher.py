    def match_department(self, text):
        """
        从文本中匹配部门
        返回: (标准部门名称, 部门编码) 或 None
        """
        # 直接查找整个文本
        if text in self.department_aliases:
            dept_name = self.department_aliases[text]
            dept_code = self.department_codes.get(dept_name)
            return dept_name, dept_code
        
        # 按长度降序尝试匹配（优先匹配长的）
        for alias in sorted(self.department_aliases.keys(), key=len, reverse=True):
            if alias in text:
                dept_name = self.department_aliases[alias]
                dept_code = self.department_codes.get(dept_name)
                return dept_name, dept_code
        
        return None, None